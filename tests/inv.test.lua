-- lib/inv.lua

test("find / count / select with names, wildcards, lists and functions", function()
  SIM.give(2, "minecraft:coal", 10)
  SIM.give(5, "minecraft:coal", 30)
  SIM.give(7, "minecraft:raw_iron", 4)
  local inv = require("lib.inv")
  eq(inv.find("minecraft:coal"), 2)
  eq(inv.count("minecraft:coal"), 40)
  eq(inv.count("*iron*"), 4)
  eq(inv.count({ "minecraft:coal", "*iron" }), 44)
  eq(inv.count(function(d) return d.count < 10 end), 4)
  eq(inv.select("*iron*"), 7)
  eq(SIM.t.sel, 7)
  eq(inv.find("minecraft:diamond"), nil)
end)

test("wildcards don't treat '-' or '.' as pattern characters", function()
  SIM.give(1, "mod-x:thing.v2", 1)
  local inv = require("lib.inv")
  eq(inv.count("mod-x:*"), 1)
  eq(inv.count("mod-x:thing.v2"), 1)
end)

test("dropMatching throws out junk and keeps the rest", function()
  SIM.give(1, "minecraft:cobblestone", 64)
  SIM.give(2, "minecraft:diamond", 3)
  SIM.give(3, "minecraft:dirt", 12)
  local inv = require("lib.inv")
  eq(inv.dropMatching(inv.junk, "down"), 76)
  eq(inv.count("minecraft:diamond"), 3)
  eq(SIM.dropped[1].where, "down")
  eq(inv.freeSlots(), 15)
end)

test("dropAllExcept keeps fuel", function()
  SIM.give(1, "minecraft:coal", 5)
  SIM.give(2, "minecraft:raw_gold", 7)
  local inv = require("lib.inv")
  eq(inv.dropAllExcept({ "minecraft:coal" }, "front"), 7)
  eq(inv.count("minecraft:coal"), 5)
end)

test("compact merges part stacks", function()
  SIM.give(1, "minecraft:coal", 20)
  SIM.give(9, "minecraft:coal", 20)
  SIM.give(12, "minecraft:raw_iron", 5)
  local inv = require("lib.inv")
  eq(inv.compact(), 1)
  eq(SIM.t.inv[1].count, 40)
  eq(SIM.t.inv[9], nil)
end)

test("refuel burns only what is needed and keeps the empty bucket", function()
  SIM.give(1, "minecraft:lava_bucket", 1)
  SIM.give(2, "minecraft:coal", 10)
  local inv = require("lib.inv")
  eq(inv.refuel(1100), 1160, "1000 from lava + 2 coal")
  eq(SIM.t.inv[1].name, "minecraft:bucket")
  eq(inv.count("minecraft:coal"), 8)
end, { fuel = 0 })

test("refuel with an allow list skips other fuels", function()
  SIM.give(1, "minecraft:coal_block", 1)
  SIM.give(2, "minecraft:charcoal", 4)
  local inv = require("lib.inv")
  eq(inv.refuel(100, "minecraft:charcoal"), 160)
  eq(inv.count("minecraft:coal_block"), 1)
end, { fuel = 0 })
