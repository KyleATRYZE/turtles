-- lib/move.lua

test("forward digs a block, tracks position and saves it", function()
  SIM.block(0, 64, -1, "minecraft:stone")
  local move = require("lib.move")
  move.set(0, 64, 0, "north")
  ok(move.forward())
  eq(SIM.t.z, -1, "turtle z")
  eq(move.pos.z, -1, "tracked z")
  eq(SIM.dug[1], "minecraft:stone", "dug")
  has(SIM.files[".move"], "z = -1", "saved state")
end)

test("a gravel column is dug until the way is clear", function()
  SIM.fill(0, 64, -1, 0, 67, -1, "minecraft:gravel")
  local move = require("lib.move")
  move.set(0, 64, 0, 0)
  ok(move.forward())
  eq(#SIM.dug, 4, "gravel blocks dug")
  eq(SIM.t.z, -1)
end)

test("never digs a turtle: waits, then gives up with a reason", function()
  SIM.block(0, 64, -1, "computercraft:turtle_normal")
  local move = require("lib.move")
  move.set(0, 64, 0, 0)
  local done, why = move.forward()
  eq(done, false)
  eq(why, "protected:computercraft:turtle_normal")
  eq(#SIM.dug, 0, "nothing dug")
  ok(SIM.time >= 4, "it waited before giving up")
end)

test("'Cannot leave loaded world' is reported as unloaded, straight away", function()
  SIM.loaded = function(x, y, z) return z > -2 end
  local move = require("lib.move")
  move.set(0, 64, 0, 0)
  local done, why, steps = move.forward(5)
  eq(done, false)
  eq(why, "unloaded")
  eq(steps, 1, "steps taken before the edge")
end)

