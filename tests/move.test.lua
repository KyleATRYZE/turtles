test("goTo with travelY goes down to the road first, then across, then up", function()
  local move = require("lib.move")
  local path = {}
  move.setup({ onMove = function(p) path[#path + 1] = p end })
  move.set(0, 64, 0, 0)
  ok(move.goTo(5, 60, -3, { travelY = 52, face = "south" }))
  eq(SIM.t.x, 5) eq(SIM.t.y, 60) eq(SIM.t.z, -3)
  eq(move.pos.f, 2, "ends facing south")
  -- every horizontal move happened at y = 52
  for _, p in ipairs(path) do
    if p.x ~= 0 or p.z ~= 0 then
      if not (p.x == 5 and p.z == -3) then eq(p.y, 52, "horizontal move height") end
    end
  end
end)

test("position survives a reboot", function()
  local move = require("lib.move")
  move.set(10, 70, 10, "west")
  ok(move.forward(2))
  package.loaded["lib.move"] = nil                -- "reboot"
  local again = require("lib.move")
  ok(again.load(), "restored")
  eq(again.pos.x, 8) eq(again.pos.f, 3)
end)

test("calibrate finds the facing with GPS and returns to the start", function()
  local move = require("lib.move")
  ok(move.calibrate())
  eq(move.pos.f, 1, "facing east")
  eq(SIM.t.x, 3, "back where it started")
  eq(move.known, true)
end, { x = 3, y = 64, z = 3, f = 1 })

test("calibrate turns to find a free side when the front is blocked", function()
  SIM.block(0, 64, -1, "minecraft:stone")            -- north blocked
  local move = require("lib.move")
  ok(move.calibrate())
  eq(move.pos.f, SIM.t.f, "tracked facing matches the turtle")
  eq(move.pos.f, 1, "turned to east")
end)

test("goTo refuses when the position is unknown", function()
  local move = require("lib.move")
  local done, why = move.goTo(1, 1, 1)
  eq(done, false)
  has(why, "position unknown")
end)

test("dig clears falling gravel overhead but refuses a protected block", function()
  SIM.fill(0, 65, 0, 0, 67, 0, "minecraft:gravel")
  SIM.block(0, 64, -1, "minecraft:chest")
  local move = require("lib.move")
  move.set(0, 64, 0, 0)
  ok(move.dig("up"))
  eq(#SIM.dug, 3, "whole gravel column")
  local done, why = move.dig("forward")
  eq(done, false) eq(why, "protected:minecraft:chest")
  ok(move.dig("down"), "nothing below is fine")
end)
