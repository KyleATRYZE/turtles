test("dig = false reports what is in the way", function()
  SIM.block(1, 64, 0, "minecraft:stone")
  local move = require("lib.move")
  move.setup({ dig = false })
  move.set(0, 64, 0, "east")
  local done, why = move.forward()
  eq(done, false)
  eq(why, "blocked:minecraft:stone")
end, { f = 1 })  -- the simulated turtle really faces east too

test("out of fuel calls the refuel hook", function()
  SIM.give(5, "minecraft:coal", 2)
  local move = require("lib.move")
  local inv = require("lib.inv")
  move.setup({ refuel = function() return inv.refuel(80) > 0 end })
  move.set(0, 64, 0, 0)
  ok(move.forward(3))
  eq(SIM.t.fuel, 80 - 3, "one coal burnt")
end, { fuel = 0 })

test("no fuel and nothing to burn: 'no fuel'", function()
  local move = require("lib.move")
  move.set(0, 64, 0, 0)
  local done, why = move.forward()
  eq(done, false)
  eq(why, "no fuel")
end, { fuel = 0 })

